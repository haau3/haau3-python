def header(what: str) -> str:
    return f'"""{what}\n\nGenerated by scripts/generate.py from openapi/openapi.json. Do not edit by hand.\n"""\n\n'


def docstring(text: str, indent: str) -> str:
    """A docstring from the spec's own words, which are already published."""
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').rstrip()
    lines = text.split("\n")
    if len(lines) == 1 and len(indent) + len(text) < 110:
        return f'{indent}"""{text}"""'
    body = "\n".join(f"{indent}{line}" if line.strip() else "" for line in lines[1:])
    return f'{indent}"""{lines[0]}\n{body}\n{indent}"""'


@dataclass
class Param:
    wire: str
    python: str
    required: bool
    type: str
    description: str


@dataclass
class Op:
    id: str
    method: str
    path: str
    tag: str
    docs: str
    summary: str
    description: str
    path_params: list[str]
    query: list[Param]
    body: str | None
    response: str
    expects: list[str]
    batchable: bool = False
    name: str = field(init=False)
    const: str = field(init=False)

    def __post_init__(self) -> None:
        self.name = naming.method_name(self.id)
        self.const = naming.constant_name(self.id)


class Spec:
    def __init__(self, spec: Json) -> None:
        self.spec = spec
        self.schemas: dict[str, Json] = spec["components"]["schemas"]
        self.fhir = sorted(n for n, s in self.schemas.items() if self.fhir_type(s))
        for name in self.fhir:
            if self.fhir_type(self.schemas[name]) != name:
                raise ValueError(f"the FHIR component {name} is named for another resource type")
        self.own = sorted(n for n in self.schemas if n not in self.fhir)
        self.ops = self._operations()

    @staticmethod
    def fhir_type(schema: Json | None) -> str | None:
        value = ((schema or {}).get("properties") or {}).get("resourceType", {}).get("const")
        return value if isinstance(value, str) else None

    def _component(self, ref: str) -> str:
        name = ref.rsplit("/", 1)[-1]
        if name not in self.schemas:
            raise ValueError(f"{ref} is not a component")
        return f"fhir.{name}" if name in self.fhir else name

    def _expects(self, op: Json) -> list[str]:
        """The FHIR resource types a 200 answers with; empty for any other answer, which is not checked."""
        types: set[str] = set()
        for media in (op.get("responses", {}).get("200", {}).get("content") or {}).values():
            schema = media.get("schema") or {}
            refs = [schema] if "$ref" in schema else schema.get("oneOf") or schema.get("anyOf") or []
            if not refs:
                return []
            for ref in refs:
                type_ = self.fhir_type(self.schemas.get(str(ref.get("$ref", "")).rsplit("/", 1)[-1]))
                if not type_:
                    return []
                types.add(type_)
        return sorted(types)

    def _response(self, op: Json) -> str:
        contents = list((op["responses"]["200"].get("content") or {}).values())
        if len(contents) != 1:
            raise ValueError(f"{op['operationId']}'s 200 has {len(contents)} media types")
        schema = contents[0]["schema"]
        if "$ref" in schema:
            return self._component(schema["$ref"])
        refs = schema.get("oneOf") or schema.get("anyOf")
        if refs and all("$ref" in r for r in refs):
            return "Union[" + ", ".join(self._component(r["$ref"]) for r in refs) + "]"
        raise ValueError(f"{op['operationId']}'s 200 has a schema the generator does not read")

    def _body(self, op: Json) -> str | None:
        body = op.get("requestBody")
        if not body:
            return None
        contents = list(body["content"].values())
        if len(contents) != 1:
            raise ValueError(f"{op['operationId']}'s body has {len(contents)} media types")
        schema = contents[0]["schema"]
        if "$ref" in schema:
            return self._component(schema["$ref"])
        # MedList takes a Bundle or a Parameters, each declared inline with its resourceType.
        branches = schema.get("oneOf") or []
        types = [self.fhir_type(b) for b in branches]
        if types and all(t in self.fhir for t in types):
            return "Union[" + ", ".join(f"fhir.{t}" for t in types) + "]"
        raise ValueError(f"{op['operationId']}'s body has a schema the generator does not read")

    def _query_type(self, op_id: str, param: Json) -> str:
        schema = {k: v for k, v in param["schema"].items() if k != "description"}
        if "anyOf" in schema:
            options = [self._query_type(op_id, {"schema": s}) for s in schema["anyOf"]]
            return " | ".join(options)
        kind = schema.get("type")
        if kind == "array":
            item = self._query_type(op_id, {"schema": schema["items"]})
            return f"Sequence[{item}]"
        if "enum" in schema:
            values = schema["enum"]
            literal = "Literal[" + ", ".join(repr(v) for v in values) + "]"
            # FHIR's `active=true`: a bool goes out as `true` or `false`, so either is taken.
            return f"bool | {literal}" if sorted(values) == ["false", "true"] else literal
        if kind == "string":
            return "str"
        if kind == "integer":
            return "int"
        if kind == "boolean":
            return "bool"
        raise ValueError(
            f"{op_id}: the query parameter {param.get('name')} has a schema the generator does not read: {schema}"
        )

    def _operations(self) -> list[Op]:
        docs = naming.DocsUrls()
        ops: list[Op] = []
        for path, item in self.spec["paths"].items():
            for method in ("get", "post"):
                op = item.get(method)
                if not op:
                    continue
                params = [p for p in op.get("parameters", []) if "$ref" not in p]
                query = [
                    Param(
                        wire=p["name"],
                        python=naming.python_name(p["name"]),
                        required=bool(p.get("required")),
                        type=self._query_type(op["operationId"], p),
                        description=" ".join((p.get("description") or "").split()),
                    )
                    for p in params
                    if p["in"] == "query"
                ]
                names = [p.python for p in query]
                clashes = {n for n in names if names.count(n) > 1} | (set(names) & {*OPTION_NAMES, "self", "body"})
                if clashes:
                    raise ValueError(f"{op['operationId']}: query parameters clash as {sorted(clashes)}")
                tag = (op.get("tags") or ["Other"])[0]
                ops.append(
                    Op(
                        id=op["operationId"],
                        method=method.upper(),
                        path=path,
                        tag=tag,
                        docs=docs(tag, op.get("summary") or op["operationId"]),
                        summary=op.get("summary") or "",
                        description=op.get("description") or "",
                        path_params=[p["name"] for p in params if p["in"] == "path"],
                        query=query,
                        body=self._body(op),
                        response=self._response(op),
                        expects=self._expects(op),
                    )
                )
        for op in ops:
            if op.method not in ("GET", "POST"):
                raise ValueError(f"{op.id} is {op.method}; the SDK sends GET and POST only")
        for id_ in NOT_IN_A_BATCH:
            if not any(op.id == id_ for op in ops):
                raise ValueError(f"{id_} is no longer in the spec: review NOT_IN_A_BATCH")
        for op in ops:
            op.batchable = op.path.startswith("/v1/fhir/r4/") and op.id not in NOT_IN_A_BATCH
        return sorted(ops, key=lambda o: o.id)


