def _readable_signature(op: Op) -> str:
    args = list(op.path_params)
    if op.body:
        args.append("body")
    required = [p.python for p in op.query if p.required]
    if required:
        args += ["*", *required]
    if any(not p.required for p in op.query):
        args.append("**query")
    return f"{op.name}({', '.join(args)})"


def api_md(spec: Spec) -> str:
    tags = [t["name"] for t in spec.spec.get("tags", [])]
    text = {t["name"]: t.get("description", "") for t in spec.spec.get("tags", [])}
    by_tag: dict[str, list[Op]] = {}
    for op in sorted(spec.ops, key=lambda o: (o.path, o.method)):
        by_tag.setdefault(op.tag, []).append(op)
    sections = []
    for tag in sorted(by_tag, key=lambda t: tags.index(t) if t in tags else 99):
        rows = [
            f"| [`{_readable_signature(o)}`]({o.docs}) | `{o.method} {o.path}` | {o.summary} |" for o in by_tag[tag]
        ]
        sections.append(
            "\n".join(
                [f"## {tag}", "", text.get(tag, ""), "", "| Method | Request | What it does |", "|---|---|---|", *rows]
            )
        )
    batchable = [o for o in spec.ops if o.batchable]
    excluded = " and ".join(f"`{naming.method_name(i)}`" for i in NOT_IN_A_BATCH)
    return f"""<!-- Generated by scripts/generate.py from openapi/openapi.json. Do not edit by hand. -->

# API reference

Every operation of the haau3 platform API (`{spec.spec["info"]["version"]}`) is a method on `Haau3` and on
`AsyncHaau3`, named by its operationId in snake_case. Each links to its page on docs.haau3.com, which
shows its parameters and an example exchange. Path values come first, then `body` for an operation
that takes one, and the query parameters are keyword arguments named by the API's own names in
snake_case (`name:contains` is `name_contains`, `_count` is `count`); each method's docstring gives
both. Every method also takes the per-call options `timeout`, `max_retries`, `correlation_id` and
`extra_headers`, and `client.with_response.<method>(...)` gives the request id and timing too.

`batch()` sends several of these as one request, each with its own answer or error, from the entries
`haau3.calls` makes. It takes every operation on the FHIR base except {excluded}: {len(batchable)} of the
{len(spec.ops)}. See the README's "Several requests in one".

{chr(10).join(s + chr(10) for s in sections).rstrip()}
"""


# --- the FHIR types and the components ----------------------------------------------------------


def fhir_module(spec: Spec) -> str:
    data = FHIR_ZIP.read_bytes()
    if hashlib.sha256(data).hexdigest() != FHIR_ZIP_SHA256:
        raise ValueError(f"{FHIR_ZIP} is not the HL7 schema this generator was pinned to")
    with zipfile.ZipFile(FHIR_ZIP) as archive:
        raw = archive.read("fhir.schema.json")
    if hashlib.sha256(raw).hexdigest() != FHIR_SCHEMA_SHA256:
        raise ValueError("fhir.schema.json in the zip is not the HL7 schema this generator was pinned to")
    return fhir_emit.emit(json.loads(raw), spec.fhir)


def components_module(spec: Spec) -> str:
    """The spec's own components, by datamodel-code-generator, from a copy without the bounds and formats.

    A `format: date-time` or a bound would otherwise become a type or a constraint the plain dicts
    an answer is made of cannot honour.
    """
    drop = {
        "format",
        "pattern",
        "minimum",
        "maximum",
        "minLength",
        "maxLength",
        "minItems",
        "maxItems",
        "examples",
        "example",
    }

    def trim(node: object) -> object:
        if isinstance(node, dict):
            return {k: trim(v) for k, v in node.items() if k not in drop}
        if isinstance(node, list):
            return [trim(v) for v in node]
        return node

    document = {
        "openapi": spec.spec["openapi"],
        "info": {"title": "components", "version": spec.spec["info"]["version"]},
        "paths": {},
        "components": {"schemas": {name: trim(spec.schemas[name]) for name in spec.own}},
    }
    with tempfile.TemporaryDirectory() as tmp:
        source, out = Path(tmp) / "components.json", Path(tmp) / "components.py"
        source.write_text(json.dumps(document))
        subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                "--input",
                str(source),
                "--input-file-type",
                "openapi",
                "--output",
                str(out),
                "--output-model-type",
                "typing.TypedDict",
                "--enum-field-as-literal",
                "all",
                "--use-union-operator",
                "--use-standard-collections",
                "--target-python-version",
                "3.10",
                "--disable-timestamp",
                "--parent-scoped-naming",
                "--use-field-description",
                "--use-schema-description",
                "--no-use-closed-typed-dict",
                "--formatters",
                "ruff-format",
                "--custom-file-header",
                header(
                    "The spec's own components: Scheduling's records and answers, and the problem other services answer with."
                ).rstrip()
                + "\n\n# ruff: noqa",
            ],
            check=True,
            capture_output=True,
            text=True,
            env={**os.environ, "PYTHONWARNINGS": "ignore"},
        )
        return out.read_text()


# --- writing ----------------------------------------------------------------------------------


def outputs(spec: Spec) -> dict[Path, Callable[[], str]]:
    return {
        PACKAGE / "fhir.py": lambda: fhir_module(spec),
        PACKAGE / "_components.py": lambda: components_module(spec),
        PACKAGE / "_operations.py": lambda: operations_module(spec),
        PACKAGE / "_methods.py": lambda: methods_module(spec),
        PACKAGE / "calls.py": lambda: calls_module(spec),
        PACKAGE / "types.py": lambda: types_module(spec),
        ROOT / "api.md": lambda: api_md(spec),
    }


def _format(files: dict[Path, str]) -> dict[Path, str]:
    """Each generated module through `ruff format`, so the output is the same wherever it is made."""
    with tempfile.TemporaryDirectory() as tmp:
        paths = {}
        for path, text in files.items():
            if path.suffix == ".py":
                target = Path(tmp) / path.name
                target.write_text(text)
                paths[path] = target
        subprocess.run(
            [
                sys.executable,
                "-m",
                "ruff",
                "format",
                "--quiet",
                "--config",
                str(ROOT / "pyproject.toml"),
                *map(str, paths.values()),
            ],
            check=True,
        )
        return {path: (paths[path].read_text() if path in paths else text) for path, text in files.items()}


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--check", action="store_true", help="fail when a generated file differs from what is committed"
    )
    parser.add_argument(
        "--list-outputs", action="store_true", help="print the paths of the generated files the package ships"
    )
    args = parser.parse_args(argv)
    spec = Spec(json.loads(SPEC.read_text()))
    planned = outputs(spec)
    if args.list_outputs:
        print("\n".join(str(p.relative_to(ROOT)) for p in planned if p.suffix == ".py"))
        return 0
    files = _format({path: make() for path, make in planned.items()})
    if args.check:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        for path in stale:
            old = path.read_text().splitlines() if path.exists() else []
            diff = list(
                difflib.unified_diff(
                    old, files[path].splitlines(), str(path.relative_to(ROOT)), "generated", lineterm="", n=1
                )
            )
            print("\n".join(diff[:40]), file=sys.stderr)
        if stale:
            print(
                f"Out of date: {', '.join(str(p.relative_to(ROOT)) for p in stale)}. Run scripts/generate.py.",
                file=sys.stderr,
            )
            return 1
        print("Generated files are up to date.")
        return 0
    for path, text in files.items():
        path.write_text(text)
    batchable = sum(1 for o in spec.ops if o.batchable)
    print(
        f"Generated {len(spec.ops)} methods ({batchable} batchable), {len(spec.fhir)} FHIR resource types and "
        f"{len(spec.own)} components from {spec.spec['info']['version']}."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
