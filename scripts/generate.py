def _signature(op: Op, *, for_call: bool = False) -> str:
    positional = [f"{name}: str" for name in op.path_params]
    if op.body:
        positional.append(f"body: {op.body}")
    parts = ["self", *positional] if not for_call else positional
    if positional:
        parts.append("/")
    keywords = [f"{p.python}: {p.type}" if p.required else f"{p.python}: {p.type} | None = None" for p in op.query]
    if not for_call:
        keywords += [
            "timeout: float | None = None",
            "max_retries: int | None = None",
            "correlation_id: str | None = None",
            "extra_headers: Mapping[str, str] | None = None",
        ]
    if keywords:
        parts += ["*", *keywords]
    return ", ".join(parts)


def _call_arguments(op: Op, body_name: str, prefix: str = "") -> str:
    path = "(" + "".join(f"{name}, " for name in op.path_params) + ")"
    query = "(" + "".join(f"({p.wire!r}, {p.python}), " for p in op.query) + ")"
    return f"{prefix}{op.const}, {path}, {query}, {body_name if op.body else 'None'}"


def _method_doc(op: Op) -> str:
    parts = [op.summary or op.id]
    if op.description:
        parts.append(op.description)
    parts.append(f"`{op.method} {op.path}`, {op.docs}")
    if op.query:
        lines = ["Query parameters, each with its name in the API:", ""]
        for p in op.query:
            wire = f" (`{p.wire}`)" if p.wire != p.python else ""
            required = " Required." if p.required else ""
            lines.append(f"- `{p.python}`{wire}:{required} {p.description}".rstrip())
        parts.append("\n".join(lines))
    return "\n\n".join(parts)


def _hide_body(op: Op, indent: str) -> list[str]:
    # A request body can be a patient's records; from here it is held where nothing prints it.
    return [f"{indent}hidden: Hidden[object] = Hidden(body)", f"{indent}del body"] if op.body else []


def _methods_class(ops: list[Op], *, name: str, asynchronous: bool, with_response: bool) -> str:
    client = "AsyncHaau3" if asynchronous else "Haau3"
    engine = "AsyncEngine" if asynchronous else "SyncEngine"
    lines: list[str] = [f"class {name}:"]
    if with_response:
        lines.append(
            docstring(
                f"Every method of `{client}` again, each returning a `Response` with the request id and timing as well as the answer.",
                "    ",
            )
        )
        lines += [
            "",
            '    __slots__ = ("_engine",)',
            "",
            f"    def __init__(self, engine: {engine}) -> None:",
            "        self._engine = engine",
            "",
        ]
        lines += ["    def __repr__(self) -> str:", f'        return "<{client}.with_response>"', ""]
    else:
        lines.append(
            docstring(f"Every operation of the haau3 platform API. `{client}` is the class to construct.", "    ")
        )
        lines += ["", f"    _engine: {engine}", ""]
    for op in ops:
        returns = f"Response[{op.response}]" if with_response else op.response
        prefix = "async def" if asynchronous else "def"
        lines.append(f"    {prefix} {op.name}({_signature(op)}) -> {returns}:")
        if with_response:
            lines.append(
                docstring(
                    f"`{client}.{op.name}`, returning a `Response` with the request id and timing as well as the answer.",
                    "        ",
                )
            )
        else:
            lines.append(docstring(_method_doc(op), "        "))
        lines += _hide_body(op, "        ")
        call = f"self._engine.call({_call_arguments(op, 'hidden')}, Options(timeout, max_retries, correlation_id, extra_headers))"
        if asynchronous:
            call = f"(await {call})"
        lines.append(f"        return {call}{'' if with_response else '.data'}")
        lines.append("")
    # The operations under the base a batch refuses, which the spec marks x-haau3-batchable: false.
    refused = sorted(o.name for o in ops if o.path.startswith("/v1/fhir/r4/") and not o.batchable)
    lines += _batch_overloads(client, refused, asynchronous=asynchronous, with_response=with_response)
    return "\n".join(lines).rstrip() + "\n"


def _batch_overloads(client: str, refused: list[str], *, asynchronous: bool, with_response: bool) -> list[str]:
    options = (
        "timeout: float | None = None, max_retries: int | None = None, "
        "correlation_id: str | None = None, extra_headers: Mapping[str, str] | None = None"
    )
    prefix = "async def" if asynchronous else "def"

    def returns(inner: str) -> str:
        return f"Response[{inner}]" if with_response else inner

    lines: list[str] = []
    for arity in range(BATCH_ARITIES + 1):
        params = ", ".join(f"c{i}: Call[T{i}]" for i in range(1, arity + 1))
        results = ", ".join(f"BatchResult[T{i}]" for i in range(1, arity + 1))
        positional = f"self, {params}, /" if arity else "self, /"
        lines += [
            "    @overload",
            f"    {prefix} batch({positional}, *, {options}) -> {returns(f'tuple[{results}]' if arity else 'tuple[()]')}: ...",
        ]
    lines += [
        "    @overload",
        f"    {prefix} batch(self, *calls: Call[T], {options}) -> {returns('tuple[BatchResult[T], ...]')}: ...",
        f"    {prefix} batch(self, *calls: Call[Any], {options}) -> {'Response[Any]' if with_response else 'tuple[BatchResult[Any], ...]'}:",
    ]
    if with_response:
        doc = f"`{client}.batch`, returning a `Response` with the batch's request id and timing as well as its results."
    else:
        doc = (
            "Several operations of the FHIR base in one request, each with its own answer or error, in the order given.\n\n"
            "Each entry comes from `haau3.calls`, called as the method of the same name is. A result is a\n"
            "`BatchOk` (`data`, `status`) or a `BatchError` (`error`, the `RefusedError` or `NoAnswerError`\n"
            "the call alone would have raised), typed by position for up to six entries:\n\n"
            "```python\n"
            "from haau3 import BatchOk, calls\n\n"
            f"plan, counties = {'await ' if asynchronous else ''}client.batch(\n"
            '    calls.read_insurance_plan("H2406-013-000"),\n'
            '    calls.list_insurance_plan_counties(state="NC"),\n'
            ")\n"
            "if isinstance(plan, BatchOk):\n"
            '    print(plan.data["name"])\n'
            "```\n\n"
            "Each entry is checked as the call alone is, and fails alone. An entry that fails is not\n"
            "retried; the batch itself is retried, and raises, as any call does. The API takes up to 100\n"
            "entries in up to 1 MiB and gives a batch 60 seconds. " + _named(refused) + " cannot go in a batch."
        )
    lines.append(docstring(doc, "        "))
    call = "self._engine.batch(calls, Options(timeout, max_retries, correlation_id, extra_headers))"
    if asynchronous:
        call = f"(await {call})"
    lines.append(f"        return {call}{'' if with_response else '.data'}")
    return lines


def methods_module(spec: Spec) -> str:
    ops = spec.ops
    own = sorted({o.response for o in ops if not o.response.startswith(("fhir.", "Union["))})
    typevars = "\n".join(f'T{i} = TypeVar("T{i}")' for i in range(1, BATCH_ARITIES + 1))
    parts = [
        header(
            "One method per operation, named by its operationId: on each client, and on each client's `with_response`."
        ),
        "# ruff: noqa\n",
        "from __future__ import annotations\n",
        "from collections.abc import Mapping, Sequence",
        "from typing import TYPE_CHECKING, Any, Literal, TypeVar, Union, overload\n",
        "from . import fhir",
        "from ._batch import BatchResult, Call",
        "from ._body import Hidden",
        f"from ._components import {', '.join(own)}",
        f"from ._operations import {', '.join(o.const for o in ops)}",
        "from ._response import Options, Response\n",
        "if TYPE_CHECKING:",
        "    from ._transport import AsyncEngine, SyncEngine\n",
        'T = TypeVar("T")',
        typevars,
        "\n",
        _methods_class(ops, name="SyncMethods", asynchronous=False, with_response=False),
        "\n",
        _methods_class(ops, name="AsyncMethods", asynchronous=True, with_response=False),
        "\n",
        _methods_class(ops, name="SyncWithResponse", asynchronous=False, with_response=True),
        "\n",
        _methods_class(ops, name="AsyncWithResponse", asynchronous=True, with_response=True),
    ]
    return "\n".join(parts)


def operations_module(spec: Spec) -> str:
    own = sorted({o.response for o in spec.ops if not o.response.startswith(("fhir.", "Union["))})
    lines = [
        header(
            "One Operation per operation of the spec: its method, its path and the FHIR resource types it answers with."
        ),
        "# ruff: noqa\n",
        "from __future__ import annotations\n",
        "from typing import Final, Union\n",
        "from . import fhir",
        f"from ._components import {', '.join(own)}",
        "from ._operation import Operation\n",
        f"SPEC_VERSION: Final[str] = {spec.spec['info']['version']!r}",
        '"""The version of the API\'s spec this SDK was generated from."""\n',
    ]
    for op in spec.ops:
        expects = "(" + "".join(f"{t!r}, " for t in op.expects) + ")"
        lines.append(f'{op.const}: Final[Operation[{op.response}]] = Operation("{op.method}", {op.path!r}, {expects})')
    return "\n".join(lines) + "\n"


def calls_module(spec: Spec) -> str:
    batchable = [o for o in spec.ops if o.batchable]
    lines = [
        '"""The entries of a batch: one function per operation a batch can carry, called as the client\'s method of\n'
        "the same name is, each making an entry for `batch()` instead of sending.\n\n"
        "```python\n"
        "from haau3 import calls\n\n"
        'plan, counties = client.batch(calls.read_insurance_plan("H2406-013-000"), calls.list_insurance_plan_counties(state="NC"))\n'
        "```\n\n"
        f"Every operation on the FHIR base can go in a batch except {_named([naming.method_name(i) for i in spec.not_in_a_batch()])}.\n\n"
        'Generated by scripts/generate.py from openapi/openapi.json. Do not edit by hand.\n"""\n',
        "# ruff: noqa\n",
        "from __future__ import annotations\n",
        "from collections.abc import Sequence",
        "from typing import Literal, Union\n",
        f"from ._operations import {', '.join(o.const for o in batchable)}",
        "from . import fhir",
        "from ._batch import Call, make_call",
        "from ._body import Hidden\n",
        f"__all__ = [{', '.join(repr(o.name) for o in batchable)}]\n",
    ]
    for op in batchable:
        lines.append(f"def {op.name}({_signature(op, for_call=True)}) -> Call[{op.response}]:")
        lines.append(
            docstring(
                f"{op.summary}, as one entry of a batch. Called as `Haau3.{op.name}` is.\n\n`{op.method} {op.path}`",
                "    ",
            )
        )
        lines += _hide_body(op, "    ")
        lines.append(f"    return make_call({_call_arguments(op, 'hidden')})")
        lines.append("")
    return "\n".join(lines)


def types_module(spec: Spec) -> str:
    lines = [
        header("The public type names: the spec's components, and each operation's query, body and answer."),
        "# ruff: noqa\n",
        "from __future__ import annotations\n",
        "from collections.abc import Sequence",
        "from typing import Literal, Union\n",
        "from typing_extensions import Required, TypeAlias, TypedDict\n",
        "from . import fhir",
    ]
    lines += [f"from ._components import {name} as {name}" for name in spec.own]
    lines.append("")
    names = set(spec.own)
    for op in spec.ops:
        base = naming.class_name(op.id)
        if op.query:
            lines.append(f"class {base}Query(TypedDict, total=False):")
            lines.append(
                docstring(f"The query parameters of `{op.name}`, by their Python names, to pass as `**query`.", "    ")
            )
            for p in op.query:
                lines.append(f"    {p.python}: {f'Required[{p.type}]' if p.required else p.type}")
            lines.append("")
        if op.body:
            lines.append(f"{base}Body: TypeAlias = {op.body}")
            lines.append(docstring(f"The request body of `{op.name}`.", ""))
        if f"{base}Response" not in names:
            lines.append(f"{base}Response: TypeAlias = {op.response}")
            lines.append(docstring(f"What `{op.name}` answers with.", ""))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


