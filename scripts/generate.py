def outputs(spec: Spec) -> dict[Path, Callable[[], str]]:
    return {
        PACKAGE / "fhir.py": lambda: fhir_module(spec),
        PACKAGE / "_components.py": lambda: components_module(spec),
        PACKAGE / "_operations.py": lambda: operations_module(spec),
        PACKAGE / "_methods.py": lambda: methods_module(spec),
        PACKAGE / "calls.py": lambda: calls_module(spec),
        PACKAGE / "types.py": lambda: types_module(spec),
        ROOT / "api.md": lambda: api_md(spec),
        ROOT / "openapi" / "code-samples.json": lambda: code_samples_json(spec),
    }


def _format(files: dict[Path, str]) -> dict[Path, str]:
    """Each generated module through `ruff format`, so the output is the same wherever it is made."""
    with tempfile.TemporaryDirectory() as tmp:
        paths = {}
        for path, text in files.items():
            if path.suffix == ".py":
                target = Path(tmp) / path.name
                target.write_text(text)
                paths[path] = target
        subprocess.run(
            [
                sys.executable,
                "-m",
                "ruff",
                "format",
                "--quiet",
                "--config",
                str(ROOT / "pyproject.toml"),
                *map(str, paths.values()),
            ],
            check=True,
        )
        return {path: (paths[path].read_text() if path in paths else text) for path, text in files.items()}


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--check", action="store_true", help="fail when a generated file differs from what is committed"
    )
    parser.add_argument(
        "--list-outputs", action="store_true", help="print the paths of the generated files the package ships"
    )
    args = parser.parse_args(argv)
    spec = Spec(json.loads(SPEC.read_text()))
    planned = outputs(spec)
    if args.list_outputs:
        print("\n".join(str(p.relative_to(ROOT)) for p in planned if p.suffix == ".py"))
        return 0
    files = _format({path: make() for path, make in planned.items()})
    if args.check:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        for path in stale:
            old = path.read_text().splitlines() if path.exists() else []
            diff = list(
                difflib.unified_diff(
                    old, files[path].splitlines(), str(path.relative_to(ROOT)), "generated", lineterm="", n=1
                )
            )
            print("\n".join(diff[:40]), file=sys.stderr)
        if stale:
            print(
                f"Out of date: {', '.join(str(p.relative_to(ROOT)) for p in stale)}. Run scripts/generate.py.",
                file=sys.stderr,
            )
            return 1
        print("Generated files are up to date.")
        return 0
    for path, text in files.items():
        path.write_text(text)
    batchable = sum(1 for o in spec.ops if o.batchable)
    print(
        f"Generated {len(spec.ops)} methods ({batchable} batchable), {len(spec.fhir)} FHIR resource types and "
        f"{len(spec.own)} components from {spec.spec['info']['version']}."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
