"""Writes `src/haau3/fhir.py`: FHIR R4 as TypedDicts, from HL7's own JSON Schema for FHIR 4.0.1.

Only the resource types the API's spec names are written, with every datatype they reach. Each key
is the JSON key exactly, `_birthDate` included, so an answer is typed as the dict it is. Nothing here
checks a value at runtime: these are types for a type checker and an editor, as `@types/fhir` is.

The keys a resource always has are those HL7's schema lists as required. `Bundle.entry.resource`,
`contained` and the other places FHIR allows any resource are typed `Resource`: one of the resource
types written here, or `OtherResource` for the rest, told apart by `resourceType`.
"""

# pyright: basic
# (This walks JSON documents whose shape it checks as it goes; strict mode's unknown-type rules add nothing here.)

from __future__ import annotations

import keyword
import re
from collections.abc import Iterable
from typing import Any

Json = dict[str, Any]

_INT_PRIMITIVES = {"integer", "positiveInt", "unsignedInt"}
# The elements of Resource and DomainResource, which every resource but Bundle, Binary and
# Parameters has.
_SHARED_ELEMENTS = (
    "id",
    "meta",
    "implicitRules",
    "_implicitRules",
    "language",
    "_language",
    "text",
    "contained",
    "extension",
    "modifierExtension",
)
_REF = "#/definitions/"

HEADER = '''"""FHIR R4 (4.0.1) as TypedDicts, for the resource types the haau3 platform API answers with.

Generated by scripts/generate.py from HL7's fhir.schema.json. Do not edit by hand.

These are types only: an answer is the JSON the API sent, as dicts and lists, and nothing checks its
elements at runtime. The SDK checks an answer's `resourceType` against what its operation answers
with, and no more.
"""

# ruff: noqa
# fmt: off

from typing import Literal, Union

from typing_extensions import Required, TypeAlias, TypedDict

'''


def _ref_name(ref: str) -> str:
    if not ref.startswith(_REF):
        raise ValueError(f"unexpected $ref {ref}")
    return ref[len(_REF) :]


def class_name(definition: str) -> str:
    """`Bundle_Entry` is `BundleEntry`."""
    return definition.replace("_", "")


def _first_sentence(text: str) -> str:
    text = " ".join(text.split())
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    return match.group(1) if match else text


def _docstring(text: str, indent: str) -> str:
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()
    if text.endswith('"'):
        text += " "
    return f'{indent}"""{text}"""'


def reachable(definitions: dict[str, Json], roots: Iterable[str]) -> set[str]:
    """Every definition the roots reach through `$ref`, except `ResourceList` (written as `Resource`)."""
    seen: set[str] = set()
    stack = list(roots)
    while stack:
        name = stack.pop()
        if name in seen or name == "ResourceList":
            continue
        if name not in definitions:
            raise ValueError(f"{name} is not in HL7's schema")
        seen.add(name)

        def walk(node: object) -> None:
            if isinstance(node, dict):
                ref = node.get("$ref")
                if isinstance(ref, str):
                    stack.append(_ref_name(ref))
                for value in node.values():
                    walk(value)
            elif isinstance(node, list):
                for value in node:
                    walk(value)

        walk(definitions[name])
    return seen


def _is_primitive(definition: Json) -> bool:
    return "properties" not in definition


def _primitive_type(name: str) -> str:
    if name == "boolean":
        return "bool"
    if name in _INT_PRIMITIVES:
        return "int"
    if name == "decimal":
        return "float"
    return "str"


def _inline_type(schema: Json, int_patterns: set[str]) -> str:
    """A choice-type element HL7 writes inline (`Extension.valueInteger`): its JSON type and pattern."""
    kind = schema.get("type")
    if kind == "boolean":
        return "bool"
    if kind == "string":
        return "str"
    if kind == "number":
        return "int" if schema.get("pattern") in int_patterns else "float"
    raise ValueError(f"unexpected inline schema {schema}")


def _literal(values: Iterable[str]) -> str:
    return "Literal[" + ", ".join(repr(v) for v in values) + "]"


def _type_of(schema: Json, definitions: dict[str, Json], int_patterns: set[str]) -> str:
    if "$ref" in schema:
        target = _ref_name(schema["$ref"])
        if target == "ResourceList":
            return '"Resource"'
        if _is_primitive(definitions[target]):
            return _primitive_type(target)
        return f'"{class_name(target)}"'
    if "const" in schema:
        return _literal([schema["const"]])
    if "enum" in schema:
        return _literal(schema["enum"])
    if schema.get("type") == "array":
        return f"list[{_type_of(schema['items'], definitions, int_patterns)}]"
    return _inline_type(schema, int_patterns)


def emit(schema: Json, roots: list[str]) -> str:
    """The module, for these root resource types."""
    definitions: dict[str, Json] = schema["definitions"]
    int_patterns = {definitions[name]["pattern"] for name in _INT_PRIMITIVES}
    names = reachable(definitions, roots)
    complex_names = sorted(n for n in names if not _is_primitive(definitions[n]))
    classes = {class_name(n) for n in complex_names}
    if len(classes) != len(complex_names):
        raise ValueError("two definitions share a class name once underscores are dropped")
    resource_list = [_ref_name(r["$ref"]) for r in definitions["ResourceList"]["oneOf"]]
    others = [n for n in resource_list if n not in roots]
    if "OtherResource" in classes or "Resource" in classes:
        raise ValueError("a definition is named OtherResource or Resource")

    out = [HEADER]
    for name in complex_names:
        out.append(_class(name, definitions[name], definitions, int_patterns))
    out.append(_other_resource(others, definitions, int_patterns))
    members = ", ".join(class_name(n) for n in roots) + ", OtherResource"
    out.append(
        f"Resource: TypeAlias = Union[{members}]\n"
        '"""Any FHIR resource: one of the types above, told apart by `resourceType`, or `OtherResource`."""\n'
    )
    return "\n\n".join(out)


def _class(name: str, definition: Json, definitions: dict[str, Json], int_patterns: set[str]) -> str:
    required = set(definition.get("required", []))
    lines = [f"class {class_name(name)}(TypedDict, total=False):"]
    lines.append(_docstring(definition.get("description", name), "    "))
    for key, schema in definition["properties"].items():
        if not key.isidentifier() or keyword.iskeyword(key):
            raise ValueError(f"{name}.{key} cannot be a TypedDict key in class syntax")
        type_ = _type_of(schema, definitions, int_patterns)
        lines.append(f"    {key}: {f'Required[{type_}]' if key in required else type_}")
        if schema.get("description"):
            lines.append(_docstring(_first_sentence(schema["description"]), "    "))
    return "\n".join(lines) + "\n"


def _other_resource(others: list[str], definitions: dict[str, Json], int_patterns: set[str]) -> str:
    """Any resource type the API's spec does not name, with the elements every resource has."""
    lines = [
        "class OtherResource(TypedDict, total=False):",
        '    """A resource of a type the haau3 platform API does not answer with, as it may appear in a Bundle or `contained`."""',
        f"    resourceType: Required[{_literal(others)}]",
    ]
    # HL7's schema writes no Resource or DomainResource definition; every DomainResource repeats
    # their elements, so they are read from one (Account).
    shared = definitions["Account"]["properties"]
    for key in _SHARED_ELEMENTS:
        lines.append(f"    {key}: {_type_of(shared[key], definitions, int_patterns)}")
    return "\n".join(lines) + "\n"
